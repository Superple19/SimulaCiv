"""Validate the generated-artifact manifest and its local gate coverage."""

from __future__ import annotations

import re
import tomllib
from pathlib import Path

from .provenance import ROOT


MANIFEST = Path("analysis/simciv_analysis/generated_artifacts.toml")
GENERATED_BY = re.compile(r"(?mi)^\s*Generated by\s+\[[^\]]+\]\(([^)]+\.py)\)")
GENERATED_REGION = re.compile(r"<!--\s*(?:BEGIN|END) GENERATED\b", re.IGNORECASE)
JUST_RECIPE = re.compile(r"^([A-Za-z0-9_-]+)(?:\s+[^:]+)?\s*:(.*)$")
JUST_CALL = re.compile(r"^\s+just\s+([A-Za-z0-9_-]+)(?:\s|$)")
PREPUSH_HOOK = re.compile(r"(?ms)^\s{6}- id:.*?(?=^\s{6}- id:|\Z)")


def load_artifacts(root: Path = ROOT) -> list[dict[str, str]]:
    data = tomllib.loads((root / MANIFEST).read_text(encoding="utf-8"))
    rows = data.get("artifact")
    if not isinstance(rows, list):
        raise ValueError("generated-artifact manifest must contain [[artifact]] entries")
    return rows


def _just_graph(text: str) -> dict[str, set[str]]:
    graph: dict[str, set[str]] = {}
    current: str | None = None
    for line in text.splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if not line[0].isspace():
            match = JUST_RECIPE.match(line)
            current = match.group(1) if match else None
            if current:
                dependencies = re.findall(r"[A-Za-z0-9_-]+", match.group(2).split("#", 1)[0])
                graph.setdefault(current, set()).update(dependencies)
            continue
        if current:
            match = JUST_CALL.match(line)
            if match:
                graph.setdefault(current, set()).add(match.group(1))
    return graph


def _prepush_roots(config: str) -> set[str]:
    roots = set()
    for block in PREPUSH_HOOK.findall(config):
        if not re.search(r"(?m)^\s*stages:\s*\[[^]]*\bpre-push\b[^]]*\]", block):
            continue
        match = re.search(r"(?m)^\s*entry:\s*just\s+([A-Za-z0-9_-]+)\b", block)
        if match:
            roots.add(match.group(1))
    return roots


def reachable_targets(justfile: str, precommit: str) -> set[str]:
    graph = _just_graph(justfile)
    pending = {"check", "check-local-data", *_prepush_roots(precommit)}
    reached = set()
    while pending:
        target = pending.pop()
        if target in reached:
            continue
        reached.add(target)
        pending.update(graph.get(target, set()) - reached)
    return reached


def check_generated_artifacts(root: Path = ROOT) -> list[str]:
    errors: list[str] = []
    try:
        artifacts = load_artifacts(root)
    except (OSError, ValueError, tomllib.TOMLDecodeError) as error:
        return [f"could not load generated-artifact manifest: {error}"]

    justfile = (root / "justfile").read_text(encoding="utf-8")
    precommit = (root / ".pre-commit-config.yaml").read_text(encoding="utf-8")
    targets = set(re.findall(r"^([A-Za-z0-9_-]+)(?:\s+[^:\n]+)?:", justfile, re.MULTILINE))
    reachable = reachable_targets(justfile, precommit)
    by_file: dict[str, dict[str, str]] = {}
    registered_generators: set[str] = set()
    for row in artifacts:
        file, generator, check = (str(row.get(key, "")) for key in ("file", "generator", "check"))
        if not file or not generator or not check:
            errors.append(f"generated-artifact entry needs file, generator, and check: {row}")
            continue
        if file in by_file:
            errors.append(f"duplicate generated-artifact registration: {file}")
            continue
        by_file[file] = row
        registered_generators.add(generator)
        if not (root / file).is_file():
            errors.append(f"generated artifact is missing: {file}")
        if not (root / generator).is_file():
            errors.append(f"generator is missing for {file}: {generator}")
        if check not in targets:
            errors.append(f"check target {check} is missing for {file}")
        elif check not in reachable:
            errors.append(f"check target {check} for {file} is unreachable from check, check-local-data, or pre-push hooks")

    documents = [root / "README.md", *root.joinpath("docs").rglob("*.md"), *root.joinpath("docs").rglob("*.qmd")]
    for document in documents:
        if "superseded" in document.parts:
            continue
        try:
            relative = document.relative_to(root).as_posix()
            text = document.read_text(encoding="utf-8")
        except (OSError, ValueError) as error:
            errors.append(f"could not inspect generated-looking document {document}: {error}")
            continue
        generated_links = list(GENERATED_BY.finditer(text))
        looks_generated = bool(generated_links or GENERATED_REGION.search(text))
        if looks_generated and relative not in by_file:
            errors.append(f"generated-looking file is not registered: {relative}")
        if relative in by_file:
            for match in generated_links:
                source = (document.parent / match.group(1)).resolve()
                try:
                    source_relative = source.relative_to(root.resolve()).as_posix()
                except ValueError:
                    errors.append(f"generated-by link escapes repository: {relative}: {match.group(1)}")
                    continue
                if source_relative not in registered_generators:
                    errors.append(f"generated-by source has no manifest generator: {relative}: {source_relative}")
    return errors


def main() -> int:
    errors = check_generated_artifacts()
    if errors:
        print("\n".join(errors))
        return 1
    print(f"{len(load_artifacts())} generated artifacts have committed generators and reachable check targets")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
