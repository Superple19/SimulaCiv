GENERATED_BY = re.compile(r"generated by\s+\[[^\]]+\]\(([^)]+\.py)\)", re.IGNORECASE)


def check_generated_artifacts(root: Path = ROOT) -> list[str]:
    justfile = (root / "justfile").read_text(encoding="utf-8")
    targets = set(re.findall(r"^([A-Za-z0-9_-]+)(?:\s+[^:\n]+)?:", justfile, re.MULTILINE))
    errors = []
    for artifact, (generator, target) in ARTIFACTS.items():
        if not (root / artifact).is_file():
            errors.append(f"generated artifact is missing: {artifact}")
        if not (root / generator).is_file():
            errors.append(f"generator is missing for {artifact}: {generator}")
        if target not in targets:
            errors.append(f"check target {target} is missing for {artifact}")

    for directory in (root / "docs" / "reproducibility", root / "docs" / "data"):
        documents = [*directory.rglob("*.md"), *directory.rglob("*.qmd")]
        for document in documents:
            if "superseded" in document.parts:
                continue
            text = document.read_text(encoding="utf-8")
            for match in GENERATED_BY.finditer(text):
                link = match.group(1)
                generator = (document.parent / link).resolve()
                try:
                    relative = generator.relative_to(root).as_posix()
                except ValueError:
                    errors.append(f"generated-by link escapes repository: {document.relative_to(root)}: {link}")
                    continue
                if not generator.is_file():
                    errors.append(f"generated-by source is missing: {document.relative_to(root)}: {link}")
                elif not any(source == relative for source, _ in ARTIFACTS.values()):
                    errors.append(f"generated-by source has no registered check target: {relative}")
    return errors


def main() -> int:
    errors = check_generated_artifacts()
    if errors:
        print("\n".join(errors))
        return 1
    print(f"{len(ARTIFACTS)} generated artifacts have committed generators and check targets")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
