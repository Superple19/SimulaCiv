from pathlib import Path

from simciv_analysis.generated_artifacts import check_generated_artifacts


def _generated_artifact_fixture(tmp_path: Path, *, reachable: bool = True):
    check_recipe = "check: inventory-check\n" if reachable else "check:\n"
    (tmp_path / "justfile").write_text(check_recipe + "inventory-check:\n    true\n", encoding="utf-8")
    (tmp_path / ".pre-commit-config.yaml").write_text("repos: []\n", encoding="utf-8")
    (tmp_path / "README.md").write_text("fixture\n", encoding="utf-8")
    (tmp_path / "docs/reproducibility").mkdir(parents=True)
    (tmp_path / "docs/reproducibility/report.md").write_text(
        "Generated by [`maker.py`](../../analysis/simciv_analysis/maker.py).\n",
        encoding="utf-8",
    )
    (tmp_path / "analysis/simciv_analysis").mkdir(parents=True)
    (tmp_path / "analysis/simciv_analysis/maker.py").write_text("", encoding="utf-8")
    (tmp_path / "analysis/simciv_analysis/generated_artifacts.toml").write_text(
        '[[artifact]]\nfile = "docs/reproducibility/report.md"\n'
        'generator = "analysis/simciv_analysis/maker.py"\ncheck = "inventory-check"\n',
        encoding="utf-8",
    )


def test_generated_artifacts_have_generators_and_reachable_check_targets(tmp_path: Path):
    _generated_artifact_fixture(tmp_path)

    errors = check_generated_artifacts(tmp_path)

    assert errors == []


def test_generated_artifact_check_fails_if_target_is_not_reachable(tmp_path: Path):
    _generated_artifact_fixture(tmp_path, reachable=False)

    errors = check_generated_artifacts(tmp_path)

    assert any("unreachable from check" in error for error in errors)


def test_generated_looking_file_must_be_registered(tmp_path: Path):
    _generated_artifact_fixture(tmp_path)
    (tmp_path / "docs/reproducibility/unregistered.md").write_text(
        "<!-- BEGIN GENERATED orphan -->\n", encoding="utf-8"
    )

    errors = check_generated_artifacts(tmp_path)

    assert any("generated-looking file is not registered" in error for error in errors)


def test_reconstruction_inventory_has_unique_columns():
    from csv import reader
    from io import StringIO

    from simciv_analysis.provenance import ROOT

    header = next(reader(StringIO((ROOT / "docs/reproducibility/M2_M3_EVIDENCE_RECONSTRUCTION.csv").read_text(encoding="utf-8-sig"))))
    assert len(header) == len(set(header))
